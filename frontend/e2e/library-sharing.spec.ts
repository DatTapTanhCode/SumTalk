import { expect, test } from '@playwright/test'
import { randomUUID } from 'node:crypto'

test.use({ timezoneId: 'UTC', actionTimeout: 5000 })

test('organizes a private library and revokes an accountless guest link', async ({ page, browser }) => {
  const oldId = randomUUID()
  const newId = randomUUID()
  const oldMeeting = `/api/meetings/${oldId}`
  const newMeeting = `/api/meetings/${newId}`
  await page.request.put(oldMeeting, { data: { title: 'Planning session', started_at: '2024-05-10T12:00:00Z' } })
  await page.request.put(newMeeting, { data: { title: 'Weekly review' } })
  const guest = await browser.newContext()
  try {
    await page.goto(`/meetings/${oldId}`)
    await page.getByRole('textbox', { name: 'Private tags' }).fill('Client A')
    await page.getByRole('button', { name: 'Add tag' }).click()
    await expect(page.getByRole('button', { name: 'Remove tag Client A' })).toBeVisible()
    await page.getByRole('button', { name: 'Planning session' }).click()
    const title = page.getByRole('textbox', { name: 'Meeting title' })
    await title.fill('Client planning')
    await title.press('Enter')
    await expect(page.getByRole('heading', { name: 'Client planning' })).toBeVisible()
    await page.goto('/')
    await page.getByLabel('Sort meetings').selectOption('oldest')
    await expect(page.getByRole('link', { name: /^Open / }).first()).toHaveAccessibleName('Open Client planning')
    await page.getByLabel('Sort meetings').selectOption('newest')
    await expect(page.getByRole('link', { name: /^Open / }).first()).toHaveAccessibleName('Open Weekly review')
    await page.getByRole('combobox', { name: 'Tag', exact: true }).selectOption('Client A')
    await expect(page.getByRole('link', { name: 'Open Weekly review' })).toHaveCount(0)
    await page.getByRole('combobox', { name: 'Tag', exact: true }).selectOption('')
    await page.getByLabel('Search meetings').fill('PLANNING')
    await expect(page.getByRole('link', { name: 'Open Weekly review' })).toHaveCount(0)
    await page.getByLabel('Search meetings').fill('')
    await page.getByLabel('Through').fill('2024-05-09')
    await expect(page.getByText('No meetings match')).toBeVisible()
    await page.getByLabel('Through').fill('2024-05-10')
    await page.getByLabel('From', { exact: true }).fill('2024-05-10')
    await page.getByRole('combobox', { name: 'Tag', exact: true }).selectOption('Client A')
    await page.getByLabel('Search meetings').fill('PLANNING')
    await expect(page.getByRole('link', { name: 'Open Weekly review' })).toHaveCount(0)
    await page.getByRole('link', { name: 'Open Client planning' }).click()
    await page.getByRole('button', { name: 'Remove tag Client A' }).click()
    await expect(page.getByRole('button', { name: 'Remove tag Client A' })).toHaveCount(0)
    await page.getByRole('button', { name: 'Share', exact: true }).click()
    await page.getByRole('button', { name: 'Create share link' }).click()
    const url = await page.getByLabel('Read-only share link').inputValue()
    const reader = await guest.newPage()
    await reader.goto(url)
    await expect(reader.getByRole('heading', { name: 'Transcript' })).toBeVisible()
    await expect(reader.getByText('Client planning')).toHaveCount(0)
    await expect(reader.getByRole('button', { name: /Share|Delete|Rename/ })).toHaveCount(0)
    await page.getByRole('button', { name: 'Turn off link' }).click()
    await expect(page.getByRole('button', { name: 'Create share link' })).toBeVisible()
    await reader.reload()
    await expect(reader.getByRole('alert')).toHaveText('Share link is unavailable')
  } finally {
    await guest.close()
    await page.request.delete(oldMeeting)
    await page.request.delete(newMeeting)
  }
})
